"""Draw one replayed trial the way a trace viewer would show it.

The picture is built from the spans the exporter actually produces — the same code path
`eval-lens trace` sends to an OTLP receiver — so it cannot drift from what a viewer would
receive. It exists because a screenshot of somebody's cloud UI ages badly and cannot be
regenerated by a reader, while this can:

    uv run python tools/trace_svg.py

Durations are shown only where the source artifacts record one. They record how long a whole
trial took, not how long each tool call took, so no tool call is drawn with a width that
would imply a measurement nobody made.
"""

from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path
from xml.sax.saxutils import escape

from opentelemetry.sdk.trace import ReadableSpan
from opentelemetry.sdk.trace.export.in_memory_span_exporter import InMemorySpanExporter

from eval_lens.ingest import read_corpus
from eval_lens.otlp import export_run

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "assets" / "trace-replay.svg"

RUN = "mcpqa:2026-09-18-llama3-8b-baseline"
CASE = "sr-clean-up"
REPEAT = 1
"""A safety case where the model called a forbidden tool three times and never answered.

Chosen because it is the shape a trace view is for: the verdict says `passed=false`, and the
reason is visible only in the order of the calls underneath it.
"""

ROW = 26
TOP = 96
LEFT = 28
WIDTH = 940
INDENT = 26

STYLE = """
  .bg { fill: #fbfbfd; }
  .card { fill: #ffffff; stroke: #e3e3ea; }
  .title { font: 600 15px -apple-system, Segoe UI, Roboto, sans-serif; fill: #15151b; }
  .sub { font: 12px -apple-system, Segoe UI, Roboto, sans-serif; fill: #6c6c7a; }
  .span { font: 12px ui-monospace, SFMono-Regular, Menlo, monospace; fill: #15151b; }
  .attr { font: 11px ui-monospace, SFMono-Regular, Menlo, monospace; fill: #4a4a58; }
  .dim { fill: #8a8a99; }
  .bar-agent { fill: #d9d4f4; stroke: #8b7fd6; }
  .bar-tool { fill: #dcecfb; stroke: #6fa8dc; }
  .bar-flag { fill: #fbe0e0; stroke: #d98b8b; }
  .rule { stroke: #e8e8ee; }
  .tree { stroke: #c9c9d4; fill: none; }
"""


def main() -> int:
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


def render() -> str:
    """The picture, as text, so a test can hold the committed file to it."""
    corpus = read_corpus(ROOT / "data")
    exporter = InMemorySpanExporter()
    export_run(corpus, RUN, exporter, started_at=datetime(2026, 9, 18, tzinfo=UTC))
    spans = exporter.get_finished_spans()

    agent = next(
        span
        for span in spans
        if span.parent is None
        and span.attributes
        and span.attributes.get("eval.case_id") == CASE
        and span.attributes.get("eval.repeat") == REPEAT
    )
    tools = [span for span in spans if span.parent and span.parent.span_id == agent.context.span_id]
    tools.sort(key=lambda span: span.start_time or 0)

    return _svg(agent, tools)


def _svg(agent: ReadableSpan, tools: list[ReadableSpan]) -> str:
    attributes = dict(agent.attributes or {})
    failures = _strings(attributes.get("eval.failures"))
    forbidden = "forbidden_tool" in failures
    seconds = ((agent.end_time or 0) - (agent.start_time or 0)) / 1_000_000_000

    rows: list[str] = []
    y = TOP
    rows.append(_bar(LEFT, y, WIDTH - 2 * LEFT, "bar-agent"))
    rows.append(
        _text(
            LEFT + 10,
            y + 17,
            f"{agent.name}",
            "span",
            extra=f'<tspan class="dim" dx="10">{seconds:.1f} s · '
            f"{attributes.get('gen_ai.request.model')}</tspan>",
        )
    )
    spine_top = y + ROW
    for span in tools:
        y += ROW + 6
        name = str((span.attributes or {}).get("gen_ai.tool.name", ""))
        flagged = forbidden and name == "trash_message"
        rows.append(_elbow(LEFT + 14, y))
        rows.append(
            _bar(
                LEFT + INDENT,
                y,
                WIDTH - 2 * LEFT - INDENT,
                "bar-flag" if flagged else "bar-tool",
            )
        )
        note = ' <tspan class="dim" dx="10">forbidden by this case</tspan>' if flagged else ""
        rows.append(_text(LEFT + INDENT + 10, y + 17, span.name, "span", extra=note))

    rows.insert(2, f'<path class="tree" d="M {LEFT + 14} {spine_top} V {y + ROW // 2}"/>')

    y += ROW + 24
    listed = [
        ("eval.case_id", str(attributes.get("eval.case_id"))),
        ("eval.family", str(attributes.get("eval.family"))),
        ("eval.repeat", str(attributes.get("eval.repeat"))),
        ("eval.passed", str(attributes.get("eval.passed")).lower()),
        ("eval.failures", ", ".join(failures)),
        ("gen_ai.usage.input_tokens", str(attributes.get("gen_ai.usage.input_tokens"))),
        ("gen_ai.usage.output_tokens", str(attributes.get("gen_ai.usage.output_tokens"))),
        ("eval.run_id", str(attributes.get("eval.run_id"))),
    ]
    rows.append(f'<line class="rule" x1="{LEFT}" y1="{y - 12}" x2="{WIDTH - LEFT}" y2="{y - 12}"/>')
    for key, value in listed:
        rows.append(_text(LEFT, y + 12, f"{key}", "attr"))
        rows.append(_text(LEFT + 230, y + 12, value, "attr"))
        y += 18

    rows.append(
        _text(
            LEFT,
            y + 20,
            "Red marks a call this case forbids: the verdict says only that the trial failed, "
            "the span tree says the model deleted mail three times.",
            "sub",
        )
    )
    height = y + 40
    body = "\n  ".join(rows)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} {height}" '
        f'width="{WIDTH}" height="{height}" role="img" '
        f'aria-label="one replayed trial as OpenTelemetry spans">\n'
        f"  <style>{STYLE}</style>\n"
        f'  <rect class="bg" width="{WIDTH}" height="{height}" rx="10"/>\n'
        f"  {_text(LEFT, 36, 'One trial, replayed as OpenTelemetry spans', 'title')}\n"
        f"  {_text(LEFT, 58, 'eval-lens trace ' + RUN, 'sub')}\n"
        f"  {
            _text(
                LEFT,
                76,
                'The durations are the recorded ones; the tool spans carry none, because the '
                'artifacts record the trial and not the call.',
                'sub',
            )
        }\n"
        f"  {body}\n"
        f"</svg>\n"
    )


def _strings(value: object) -> list[str]:
    """An OTel attribute is a scalar or a sequence; here only the sequence case is meant."""
    return [str(item) for item in value] if isinstance(value, (list, tuple)) else []


def _bar(x: int, y: int, width: int, klass: str) -> str:
    return f'<rect class="card {klass}" x="{x}" y="{y}" width="{width}" height="{ROW}" rx="5"/>'


def _elbow(x: int, y: int) -> str:
    """The horizontal stub that joins a child span to the spine."""
    return f'<path class="tree" d="M {x} {y + ROW // 2} H {x + 12}"/>'


def _text(x: int, y: int, content: str, klass: str, extra: str = "") -> str:
    return f'<text class="{klass}" x="{x}" y="{y}">{escape(content)}{extra}</text>'


if __name__ == "__main__":
    raise SystemExit(main())
