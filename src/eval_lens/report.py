"""The report, assembled from the queries and nothing else.

No number in it is typed by hand, and none of it depends on when it was generated: the
same corpus produces the same file, which is what lets CI fail when the text and the data
disagree.
"""

from __future__ import annotations

from eval_lens import metrics, queries
from eval_lens.comparisons import Comparison
from eval_lens.model import Corpus
from eval_lens.store import Store

HEADER = """# What these two suites are worth as instruments

Generated by `eval-lens report` from the runs in `data/`. Every number below comes from a
query in `sql/` or its twin in `src/eval_lens/metrics.py`; the two are held equal by a test.
"""

LIMITS = """## What this does not show

The corpus is two suites written by one person, scored by two small local models over five
days. Everything here describes those suites: a saturated case is saturated *for these
models*, and a case that never moved might move against a better one. The same measurements
on a suite with more models and more runs would be worth more, and the queries would not
change.

Nothing here judges the models. A suite that cannot separate two policies is a statement
about the suite; which policy is better is a question these runs already answered elsewhere.
"""


def render(store: Store, corpus: Corpus, comparisons: list[Comparison]) -> str:
    parts = [
        HEADER,
        _corpus(store, comparisons),
        _information(store),
        _noise(store),
        _drift(store),
        _cost(store),
        _variance(corpus, comparisons),
        _failures(store),
        _pruning(corpus, comparisons),
        LIMITS,
    ]
    return "\n".join(parts).rstrip() + "\n"


PROJECT_SHORT = {"agent-eval-lab": "lab", "mcp-connector-testkit": "kit"}


def short_labels(comparisons: list[Comparison]) -> dict[str, str]:
    """Readable names for a table: the factor, plus only the settings that differ.

    A full configuration fingerprint belongs in the data, not in a column heading.
    """
    by_project: dict[str, list[Comparison]] = {}
    for comparison in comparisons:
        by_project.setdefault(comparison.project, []).append(comparison)

    labels: dict[str, str] = {}
    for project, group in by_project.items():
        settings = [_settings(comparison.config) for comparison in group]
        keys = {key for setting in settings for key in setting}
        varying = sorted(key for key in keys if len({setting.get(key) for setting in settings}) > 1)
        prefix = PROJECT_SHORT.get(project, project)
        for comparison, setting in zip(group, settings, strict=True):
            suffix = " ".join(
                key if setting.get(key) == "yes" else f"{key}={setting.get(key, '—')}"
                for key in varying
            )
            labels[comparison.name] = f"{prefix}: {comparison.factor}" + (
                f" [{suffix}]" if suffix else ""
            )
    return labels


def _settings(config: str) -> dict[str, str]:
    """`temperature=0;repeats=3;harness-v2` → a dictionary, bare tokens included."""
    pairs: dict[str, str] = {}
    for part in config.split(";"):
        if not part:
            continue
        key, separator, value = part.partition("=")
        pairs[key] = value if separator else "yes"
    return pairs


def _table(header: list[str], rows: list[list[str]], align: str = "---") -> str:
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join(align for _ in header) + " |"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def _corpus(store: Store, comparisons: list[Comparison]) -> str:
    runs = store.query(
        "SELECT project, count() AS runs, uniqExact(model) AS models, "
        "uniqExact(suite_version) AS versions "
        "FROM runs GROUP BY project ORDER BY project"
    )
    trials = store.query(
        "SELECT r.project AS project, count() AS trials, countIf(t.error != '') AS stopped "
        "FROM trials AS t INNER JOIN runs AS r USING (run_id) GROUP BY project ORDER BY project"
    )
    stopped = {row["project"]: row for row in trials}
    rows = [
        [
            row["project"],
            str(row["runs"]),
            str(row["models"]),
            str(row["versions"]),
            str(stopped[row["project"]]["trials"]),
            str(stopped[row["project"]]["stopped"]),
        ]
        for row in runs
    ]
    return (
        "## The corpus\n\n"
        + _table(
            ["Project", "Runs", "Models", "Dataset versions", "Trials", "Cut short by a limit"],
            rows,
        )
        + f"\n\n{len(comparisons)} comparisons are derivable from it: pairs of runs that share "
        "project, dataset version, model and configuration and differ in exactly one variant. "
        "Fixture runs never enter a comparison.\n"
    )


def _information(store: Store) -> str:
    rows = store.query(
        "SELECT project, suite_version, label, count() AS cases FROM case_verdicts "
        "GROUP BY project, suite_version, label ORDER BY project, suite_version, label"
    )
    counts: dict[tuple[str, str], dict[str, int]] = {}
    for row in rows:
        counts.setdefault((row["project"], row["suite_version"]), {})[row["label"]] = row["cases"]
    labels = ["informative", "quiet", "saturated", "floored"]
    table = _table(
        ["Project", "Dataset version", *labels],
        [
            [project, version, *[str(values.get(label, 0)) for label in labels]]
            for (project, version), values in sorted(counts.items())
        ],
    )
    families = store.query(
        "SELECT project, family, count() AS cases, countIf(label = 'informative') AS informative "
        "FROM case_verdicts GROUP BY project, family HAVING informative = 0 "
        "ORDER BY cases DESC, project, family"
    )
    silent = "\n".join(
        f"- `{row['project']}` / `{row['family']}`: {row['cases']} cases, none of which ever "
        "separated two sides"
        for row in families
    )
    return (
        "## 1. Which cases carry information\n\n"
        "A case is **informative** when its pass rate differs between the two sides of a "
        "comparison. **Saturated** and **floored** cases never differ because they always pass "
        "or always fail; **quiet** ones move between runs but never between the sides of a "
        "comparison, which is dispersion without an answer.\n\n" + table + "\n\n"
        "Whole families that never separated anything:\n\n" + (silent or "- none") + "\n"
    )


def _noise(store: Store) -> str:
    rows = store.query(
        "SELECT r.project AS project, r.model AS model, "
        "sum(n.cases_with_repeats) AS cases, sum(n.mixed_cases) AS mixed "
        "FROM (" + queries.read("repeat_noise").rstrip().rstrip(";") + ") AS n "
        "INNER JOIN runs AS r ON r.run_id = n.run_id "
        "GROUP BY project, model ORDER BY project, model"
    )
    table = _table(
        ["Project", "Model", "Cases with repeats", "Cases whose repeats disagree", "Share"],
        [
            [
                row["project"],
                row["model"],
                str(row["cases"]),
                str(row["mixed"]),
                f"{row['mixed'] / row['cases']:.0%}" if row["cases"] else "—",
            ]
            for row in rows
        ],
    )
    return (
        "## 2. How much the instrument disagrees with itself\n\n"
        "Repeats of one case, under settings that did not change between them.\n\n" + table + "\n"
    )


def _drift(store: Store) -> str:
    rows = store.query(queries.read("drift"))
    table = _table(
        ["Project", "Dataset version", "Variant", "Runs", "Spread in pass rate"],
        [
            [
                row["project"],
                row["suite_version"],
                f"`{row['variant']}`",
                str(row["runs"]),
                f"{row['spread']:.0%}",
            ]
            for row in rows
        ],
    )
    worst = max((row["spread"] for row in rows), default=0.0)
    return (
        "## 3. How far the same variant moves between runs\n\n"
        "Nothing about the policy changed between these runs — only the configuration around "
        "it, and the sampling nobody pinned.\n\n" + table + "\n\n"
        f"The largest of these, {worst:.0%}, is the floor under any difference these suites "
        "report: an effect smaller than that cannot be told from the instrument shifting.\n"
    )


def total_seconds(row: dict[str, float]) -> float:
    return float(row["silent_seconds"]) + float(row["informative_seconds"])


def _cost(store: Store) -> str:
    rows = store.query(queries.read("silence_cost"))
    table = _table(
        [
            "Project",
            "Dataset version",
            "Informative",
            "Silent",
            "Never compared",
            "Time on silent cases",
        ],
        [
            [
                row["project"],
                row["suite_version"],
                str(row["informative_cases"]),
                str(row["silent_cases"]),
                str(row["uncompared_cases"]),
                (
                    f"{row['silent_seconds'] / 60:.0f} of "
                    f"{total_seconds(row) / 60:.0f} min "
                    f"({row['silent_seconds'] / total_seconds(row):.0%})"
                    if total_seconds(row)
                    else "—"
                ),
            ]
            for row in rows
        ],
    )
    return "## 4. What the silence costs\n\n" + table + "\n"


def _variance(corpus: Corpus, comparisons: list[Comparison]) -> str:
    rows = metrics.variance_split(corpus, comparisons)
    labels = short_labels(comparisons)
    table = _table(
        ["Comparison", "Between cases", "Between variants", "Residual"],
        [
            [
                f"`{labels[row.comparison]}`",
                f"{row.between_cases:.0%}",
                f"{row.between_variants:.0%}",
                f"{row.residual:.0%}",
            ]
            for row in rows
        ],
    )
    return (
        "## 5. Where the spread in verdicts comes from\n\n"
        "A crude decomposition of a binary outcome, reported as a direction rather than a "
        "measurement: the residual absorbs everything the other two terms cannot explain.\n\n"
        + table
        + "\n\nThe thing under test is usually the smallest term.\n"
    )


def _failures(store: Store) -> str:
    rows = store.query(queries.read("failure_profile"))[:10]
    table = _table(
        ["Project", "Failure", "Trials", "Runs"],
        [
            [row["project"], f"`{row['label']}`", str(row["trials"]), str(row["runs"])]
            for row in rows
        ],
    )
    silent = store.query(queries.read("silent_gates"))
    listed = "\n".join(
        f"- `{row['project']}` / `{row['gate']}`: recorded on {row['trials']} trials, "
        "failed on none"
        for row in silent
    )
    return (
        "## 6. What actually fails\n\n" + table + "\n\n"
        "Gates that are recorded on every trial and have never once failed:\n\n"
        + (listed or "- none")
        + "\n\nEither nothing in the suite breaks that rule, or the rule is written so that "
        "nothing can. Both are worth knowing, and neither is visible from a pass rate.\n"
    )


def _pruning(corpus: Corpus, comparisons: list[Comparison]) -> str:
    rows = metrics.pruning_experiment(corpus, comparisons)
    labels = short_labels(comparisons)
    table = _table(
        ["Comparison", "Kept", "Dropped", "Δ all", "Δ kept", "p all", "p kept", "Time saved"],
        [
            [
                f"`{labels[row.comparison]}`",
                str(row.kept_cases),
                str(row.dropped_cases),
                f"{row.delta_all:+.0%}",
                f"{row.delta_kept:+.0%}",
                f"{row.p_all:.3f}",
                f"{row.p_kept:.3f}",
                f"{row.time_saved:.0%}",
            ]
            for row in rows
        ],
    )
    survived = sum(row.same_verdict for row in rows)
    saved = [row.time_saved for row in rows]
    return (
        "## 7. Would the conclusions survive a shorter suite?\n\n"
        "Each comparison recomputed on the cases that *other* comparisons found informative — "
        "never on the ones it decided itself.\n\n" + table + "\n\n"
        f"Same verdict at 5% in {survived} of {len(rows)} comparisons, with "
        f"{min(saved):.0%} to {max(saved):.0%} of the running time removed. The effects get "
        "larger on the shorter suite, because the silent cases were averaging them down.\n"
    )
